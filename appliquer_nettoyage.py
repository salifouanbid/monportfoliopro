def git(*args, check=True, show=False):
    r = subprocess.run(["git", *args], text=True, capture_output=not show)
    if check and r.returncode != 0:
        print("Erreur git %s :\n%s" % (" ".join(args), (r.stderr or "").strip()))
        sys.exit(1)
    return r

def etape(n, texte): print("\n[%d] %s" % (n, texte))

def main():
    sans_push = "--sans-push" in sys.argv
    if not (os.path.isdir(".git") and os.path.exists("index.html")):
        print("Lance ce script à la racine du dépôt monportfoliopro (le dossier qui contient .git et index.html).")
        sys.exit(1)

    etape(1, "Mise à jour du dépôt local")
    r = git("pull", "--ff-only", check=False)
    print("   " + ((r.stdout or r.stderr).strip().splitlines() or ["ok"])[-1])

    etape(2, "Sauvegarde des anciennes versions (tag archive-v2)")
    git("tag", "-f", "archive-v2", "-m", "Versions V2.1 à V2.5 et brouillons, avant nettoyage")

    etape(3, "Déplacement de la photo et du CV")
    os.makedirs("images", exist_ok=True); os.makedirs("assets", exist_ok=True)
    if os.path.exists("V2.1/matof.jpg") and not os.path.exists("images/matof.jpg"):
        git("mv", "V2.1/matof.jpg", "images/matof.jpg"); print("   V2.1/matof.jpg -> images/matof.jpg")
    for nom in ("Cv2.0.pdf", "CV2.0.pdf"):
        if os.path.exists(nom) and not os.path.exists("assets/cv-anbid-salifou.pdf"):
            git("mv", nom, "assets/cv-anbid-salifou.pdf"); print("   %s -> assets/cv-anbid-salifou.pdf" % nom); break

    etape(4, "Suppression des anciennes versions et brouillons")
    for d in ("V2.1", "V2.2", "V2.3", "V2.4", "V2.5", "dechets"):
        if os.path.exists(d):
            git("rm", "-r", "-q", "-f", d, check=False); print("   supprimé : " + d)
    if git("ls-files", "CV", check=False).stdout.strip():
        git("rm", "-r", "-q", "--cached", "CV", check=False); print("   CV/ retiré du dépôt (les fichiers restent sur ton disque)")

    etape(5, "Écriture des nouveaux fichiers du site")
    with zipfile.ZipFile(io.BytesIO(base64.b64decode(FICHIERS_B64))) as z:
        for nom in z.namelist():
            with open(nom, "w", encoding="utf-8", newline="\n") as f: f.write(z.read(nom).decode("utf-8"))
            print("   écrit : " + nom)

    etape(6, "Vérification des liens locaux de index.html")
    html = open("index.html", encoding="utf-8").read()
    manquants = [m for m in re.findall(r'(?:src|href)="([^"]*)"', html)
                 if not m.startswith(("http", "mailto", "#", "data:")) and not os.path.exists(m)]
    print("   " + ("aucun lien cassé" if not manquants else "FICHIERS MANQUANTS : " + ", ".join(manquants)))

    etape(7, "Enregistrement (commit)")
    git("add", ".gitignore", "README.md", "index.html", "style.css", "script.js", "assets", "images")
    git("commit", "-q", "-m", "Nettoyage du dépôt et du site : anciennes versions archivées, liens et images corrigés, contenu simplifié")
    print("   commit créé")

    if sans_push:
        print("\nTerminé. Pour publier : git push && git push -f origin archive-v2"); return
    rep = input("\nPousser maintenant sur GitHub ? [O/n] ").strip().lower()
    if rep in ("", "o", "oui", "y", "yes"):
        git("push", show=True); git("push", "-f", "origin", "archive-v2", check=False, show=True)
        print("\nTerminé : le site se met à jour sur GitHub Pages dans une à deux minutes.")
    else:
        print("\nRien n'a été envoyé. Quand tu veux : git push && git push -f origin archive-v2")

if __name__ == "__main__":
    main()
